#!/usr/bin/env bash
# Rewrites the uv image digest that docker/Dockerfile.python-agent cannot
# read from UV_VERSION, and records that manifest-list digest.
#
# Reads UV_VERSION. Fetches the astral/uv:<UV_VERSION>-python3.13-trixie-slim
# manifest-list digest when scripts/lib/uv-image.txt is missing or names a
# different version. Rewrites that record and the @sha256: on the
# astral/uv FROM line. Exits 0 without network when the record already
# matches and the Dockerfile digest agrees.
#
# UV_IMAGE_DIGEST, when set, is used instead of a registry fetch (tests).
# REPO_ROOT, when set, is the tree to edit (tests). Otherwise the repo that
# contains this script.
#
# Usage: scripts/tools/update_uv_image.bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ -z "${REPO_ROOT:-}" ]]; then
    REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
fi

# shellcheck source=scripts/lib/versions.sh
source "$REPO_ROOT/scripts/lib/versions.sh"

UV_IMAGE_FILE="$REPO_ROOT/scripts/lib/uv-image.txt"
DOCKERFILE="$REPO_ROOT/docker/Dockerfile.python-agent"
TAG_SUFFIX="-python3.13-trixie-slim"

die() {
    echo "error: $*" >&2
    exit 1
}

# Scratch space for the rewrite. It is built here and copied over the
# target with cat, so the Dockerfile keeps its own mode (mktemp files are
# 0600 and mv would carry that onto it), and a die leaves nothing behind.
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

dockerfile_digest() {
    local line
    while IFS= read -r line || [[ -n "$line" ]]; do
        if [[ "$line" =~ ^FROM[[:space:]]+astral/uv:.*@(sha256:[0-9a-f]{64}) ]]; then
            printf '%s' "${BASH_REMATCH[1]}"
            return 0
        fi
    done <"$DOCKERFILE"
    return 1
}

read_record() {
    RECORD_VERSION=""
    RECORD_DIGEST=""
    [[ -f "$UV_IMAGE_FILE" ]] || return 0
    local line count=0 version digest
    while IFS= read -r line || [[ -n "$line" ]]; do
        [[ "$line" =~ ^# ]] && continue
        [[ -z "$line" ]] && continue
        if [[ "$line" =~ ^([0-9]+\.[0-9]+\.[0-9]+)[[:space:]]+(sha256:[0-9a-f]{64})$ ]]; then
            version="${BASH_REMATCH[1]}"
            digest="${BASH_REMATCH[2]}"
            count=$((count + 1))
        else
            die "$UV_IMAGE_FILE has a line that is not '<version> sha256:<64-hex>': $line"
        fi
    done <"$UV_IMAGE_FILE"
    [[ "$count" -eq 1 ]] || die "$UV_IMAGE_FILE must contain exactly one digest line"
    RECORD_VERSION="$version"
    RECORD_DIGEST="$digest"
}

rewrite_dockerfile_digest() {
    local digest="$1" tmp="$TMP_DIR/out"
    awk -v digest="$digest" '
        BEGIN { done = 0 }
        /^FROM / && index($0, "astral/uv:") > 0 {
            if (sub(/@sha256:[0-9a-f]+/, "@" digest)) {
                done = 1
            }
        }
        { print }
        END { if (done == 0) exit 2 }
    ' "$DOCKERFILE" >"$tmp" || die "$DOCKERFILE has no digest-pinned FROM astral/uv line"
    cat "$tmp" >"$DOCKERFILE"
}

write_record() {
    local digest="$1"
    mkdir -p "$(dirname "$UV_IMAGE_FILE")"
    cat >"$UV_IMAGE_FILE" <<EOF
# Manifest-list digest of astral/uv:<version>${TAG_SUFFIX}. Regenerated by task tools:sync-uv.
${UV_VERSION} ${digest}
EOF
}

fetch_manifest_list_digest() {
    local version="$1" token headers content_type digest
    token="$(
        curl -fsSL "https://auth.docker.io/token?service=registry.docker.io&scope=repository:astral/uv:pull" |
            sed -n 's/.*"token"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p'
    )"
    [[ -n "$token" ]] || die "Docker Hub token response had no token"
    headers="$(
        curl -fsSLI \
            -H "Authorization: Bearer ${token}" \
            -H "Accept: application/vnd.docker.distribution.manifest.list.v2+json, application/vnd.oci.image.index.v1+json" \
            "https://registry-1.docker.io/v2/astral/uv/manifests/${version}${TAG_SUFFIX}" | tr -d '\r'
    )"
    # The registry may answer with a single-platform manifest even when the
    # Accept header asks for a list, and -L can leave several response
    # headers in the output. Read the last of each, and refuse anything but
    # a manifest list or an OCI index: a single-platform digest would break
    # a multi-arch build.
    content_type="$(awk 'tolower($1) == "content-type:" { v = tolower($2) } END { print v }' <<<"$headers")"
    case "$content_type" in
        application/vnd.docker.distribution.manifest.list.v2+json* | application/vnd.oci.image.index.v1+json*) ;;
        *) die "expected a manifest list or OCI index for astral/uv:${version}${TAG_SUFFIX}, got content-type: ${content_type:-<empty>}" ;;
    esac
    digest="$(awk 'tolower($1) == "docker-content-digest:" { v = $2 } END { print v }' <<<"$headers")"
    [[ "$digest" =~ ^sha256:[0-9a-f]{64}$ ]] || die "no manifest-list digest for astral/uv:${version}${TAG_SUFFIX}"
    printf '%s' "$digest"
}

read_record

if [[ "${RECORD_VERSION:-}" == "$UV_VERSION" && -n "${RECORD_DIGEST:-}" ]]; then
    got="$(dockerfile_digest)" || true
    if [[ "${got:-}" == "$RECORD_DIGEST" ]]; then
        echo "uv image already matches $UV_VERSION" >&2
        exit 0
    fi
fi

if [[ -n "${UV_IMAGE_DIGEST:-}" ]]; then
    DIGEST="$UV_IMAGE_DIGEST"
elif [[ "${RECORD_VERSION:-}" == "$UV_VERSION" && -n "${RECORD_DIGEST:-}" ]]; then
    DIGEST="$RECORD_DIGEST"
else
    DIGEST="$(fetch_manifest_list_digest "$UV_VERSION")"
fi

[[ "$DIGEST" =~ ^sha256:[0-9a-f]{64}$ ]] || die "digest must look like sha256:<64-hex>, got: $DIGEST"

write_record "$DIGEST"
rewrite_dockerfile_digest "$DIGEST"

echo "updated uv image to $UV_VERSION ($DIGEST)" >&2
